function getValue(obj, path) {
  return path.split('.').reduce((acc, key) => acc && acc[key], obj);
}

function applyLanguage(lang) {
  const selected = translations[lang] ? lang : 'en';
  const t = translations[selected];
  const page = document.body.dataset.page || 'home';
  document.documentElement.lang = selected === 'gu' ? 'gu' : 'en';
  document.title = `${t.siteName} | ${t[`pageTitle${page.charAt(0).toUpperCase()}${page.slice(1)}`] || t.siteName}`;

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = getValue(t, element.dataset.i18n);
    if (typeof value === 'string') {
      element.textContent = value;
    }
  });

  const toggle = document.getElementById('lang-toggle');
  if (toggle) {
    toggle.textContent = selected === 'gu' ? 'English' : 'ગુજરાતી';
    toggle.setAttribute('aria-label', selected === 'gu' ? 'Switch to English' : 'Switch to Gujarati');
  }

  localStorage.setItem('karuna-language', selected);
}

const saved = localStorage.getItem('karuna-language');
applyLanguage(saved === 'gu' ? 'gu' : 'en');

const toggle = document.getElementById('lang-toggle');
if (toggle) {
  toggle.addEventListener('click', () => {
    applyLanguage(document.documentElement.lang === 'gu' ? 'en' : 'gu');
  });
}

const navToggle = document.getElementById('nav-toggle');
const navLinks = document.querySelector('.nav-links');
if (navToggle && navLinks) {
  navToggle.addEventListener('click', () => {
    const open = navLinks.classList.toggle('open');
    navToggle.setAttribute('aria-expanded', String(open));
  });
}

const contactForm = document.getElementById('contact-form');
if (contactForm) {
  contactForm.addEventListener('submit', (event) => {
    event.preventDefault();

    const name = document.getElementById('name')?.value.trim();
    const email = document.getElementById('email')?.value.trim();
    const message = document.getElementById('message')?.value.trim();
    const subject = encodeURIComponent(`Contact request from ${name || 'website visitor'}`);
    const body = encodeURIComponent([
      name ? `Name: ${name}` : '',
      email ? `Email: ${email}` : '',
      '',
      message || ''
    ].filter(Boolean).join('\n'));

    window.location.href = `mailto:karunanidhi14577@gmail.com?subject=${subject}&body=${body}`;

    const submitButton = contactForm.querySelector('button[type="submit"]');
    if (submitButton) {
      submitButton.textContent = document.documentElement.lang === 'gu' ? 'મોકલાયો' : 'Sent';
      submitButton.disabled = true;
      setTimeout(() => {
        submitButton.textContent = document.documentElement.lang === 'gu' ? 'સંદેશ મોકલો' : 'Send message';
        submitButton.disabled = false;
        contactForm.reset();
      }, 1500);
    }
  });
}
